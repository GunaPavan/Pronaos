async def _set_image_cap(
    *, gateway_url: str, admin_key: str, team_id: str, max_bytes: int | None
) -> None:
    """Set or clear the team's max_image_bytes via the admin API."""
    async with httpx.AsyncClient(base_url=gateway_url, timeout=10.0) as client:
        resp = await client.put(
            f"/v1/admin/team/{team_id}/image-cap",
            headers={"Authorization": f"Bearer {admin_key}"},
            json={"max_bytes": max_bytes},
        )
        resp.raise_for_status()


async def _one_call(
    *,
    gateway_url: str,
    api_key: str,
    model: str,
    image_url: str,
    nonce: str,
) -> tuple[int, dict[str, str], dict[str, Any]]:
    """Send one multi-modal chat completion and return (status, headers, body).

    The ``nonce`` defeats the gateway's exact-match cache so the
    upstream is always called and the image-tokens header path is
    exercised (cache hits short-circuit before the stamp).
    """
    body = {
        "model": model,
        "messages": [
            {
                "role": "user",
                "content": [
                    {
                        "type": "text",
                        "text": (
                            f"Describe this image in one short sentence. "
                            f"(call-id: {nonce})"
                        ),
                    },
                    {"type": "image_url", "image_url": {"url": image_url}},
                ],
            }
        ],
        "temperature": 0.0,
        "max_tokens": 60,
    }
    async with httpx.AsyncClient(base_url=gateway_url, timeout=60.0) as client:
        resp = await client.post(
            "/v1/chat/completions",
            headers={"Authorization": f"Bearer {api_key}"},
            json=body,
        )
    try:
        out: dict[str, Any] = resp.json()
    except ValueError:
        out = {"_raw": resp.text}
    return resp.status_code, dict(resp.headers), out


async def _main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--gateway-url", default="http://127.0.0.1:8080")
    parser.add_argument("--admin-api-key", required=True)
    parser.add_argument("--api-key", required=True)
    parser.add_argument("--team-id", required=True)
    parser.add_argument(
        "--model",
        default="groq/meta-llama/llama-4-scout-17b-16e-instruct",
        help="Vision-capable model fqmn.",
    )
    args = parser.parse_args()

    print(f"using model: {args.model}")
    image_url = _real_png_data_uri()
    print(f"image: 64x64 solid-color PNG, base64 length = {len(image_url.split(',', 1)[1])}")
    print()

    # ---- Step 1: clear any prior cap, fire vision call ----
    print("Clearing any prior image cap...")
    await _set_image_cap(
        gateway_url=args.gateway_url,
        admin_key=args.admin_api_key,
        team_id=args.team_id,
        max_bytes=None,
    )

    print(f"Calling {args.model} with the image...")
    status, headers, body = await _one_call(
        gateway_url=args.gateway_url,
        api_key=args.api_key,
        model=args.model,
        image_url=image_url,
        nonce=uuid.uuid4().hex,
    )

    image_tokens = headers.get("x-pronaos-image-tokens")
    image_count = headers.get("x-pronaos-image-count")
    routed_model = headers.get("x-pronaos-routed-model", args.model)
    content = ""
    choices = body.get("choices")
    if isinstance(choices, list) and choices:
        msg = choices[0].get("message", {}) if isinstance(choices[0], dict) else {}
        content = msg.get("content") or ""

    print(f"  HTTP status:              {status}")
    print(f"  X-Pronaos-Image-Tokens:   {image_tokens}")
    print(f"  X-Pronaos-Image-Count:    {image_count}")
    print(f"  routed model:             {routed_model}")
    print(f"  model response:           {content[:120]!r}")
    print()

    # ---- Step 2: set a tight cap, expect 422 ----
    print("Setting image cap to 50 bytes (well below the request payload)...")
    await _set_image_cap(
        gateway_url=args.gateway_url,
        admin_key=args.admin_api_key,
        team_id=args.team_id,
        max_bytes=50,
    )
    print("Retrying — should fail with 422 BEFORE any upstream call...")
    cap_status, _cap_headers, cap_body = await _one_call(
        gateway_url=args.gateway_url,
        api_key=args.api_key,
        model=args.model,
        image_url=image_url,
        nonce=uuid.uuid4().hex,
    )
    cap_detail = cap_body.get("detail") or {}
    cap_reason = cap_detail.get("type") if isinstance(cap_detail, dict) else None
    print(f"  HTTP status:              {cap_status}")
    print(f"  detail.type:              {cap_reason}")
    print()

    # Cleanup: clear the cap so the team's other workflows aren't blocked.
    await _set_image_cap(
        gateway_url=args.gateway_url,
        admin_key=args.admin_api_key,
        team_id=args.team_id,
        max_bytes=None,
    )

    print("=" * 64)
    print("Phase 41 — multi-modal image input experiment")
    print("=" * 64)
    print(f"vision call status:        {status}")
    print(f"image tokens reported:     {image_tokens}")
    print(f"image count:               {image_count}")
    print(f"cap-rejected status:       {cap_status}")
    print(f"cap-rejected reason:       {cap_reason}")
    print()

    holds = (
        status == 200
        and image_tokens is not None
        and int(image_tokens) > 0
        and image_count == "1"
        and cap_status == 422
        and cap_reason == "image_too_large"
    )
    if holds:
        print(
            f"VERDICT: claim holds — gateway accepted a multi-modal request, "
            f"forwarded the image to {args.model}, computed an image-token "
            f"cost ({image_tokens} tokens for a 64x64 PNG) and surfaced it "
            f"on the X-Pronaos-Image-Tokens header. With the per-team cap "
            f"set to 50 bytes (below the request's payload), the same call "
            f"returned 422 'image_too_large' BEFORE the upstream provider "
            f"was touched — the per-tenant size gate works end-to-end."
        )
        sys.exit(0)

    reasons: list[str] = []
    if status != 200:
        reasons.append(
            f"vision call failed (status={status}): {str(body)[:200]}"
        )
    if image_tokens is None or int(image_tokens or "0") <= 0:
        reasons.append(
            f"X-Pronaos-Image-Tokens header missing or zero (got {image_tokens!r})"
        )
    if image_count != "1":
        reasons.append(
            f"X-Pronaos-Image-Count expected '1', got {image_count!r}"
        )
    if cap_status != 422:
        reasons.append(
            f"cap-rejected status should be 422, got {cap_status}"
        )
    if cap_reason != "image_too_large":
        reasons.append(
            f"cap-rejected reason should be 'image_too_large', got {cap_reason!r}"
        )
    print(f"VERDICT: claim fails — {'; '.join(reasons)}.")
    sys.exit(1)


if __name__ == "__main__":
    asyncio.run(_main())
